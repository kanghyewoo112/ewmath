def _tbl(head, rows, widths, fs=11.5, hl=None, grey=()):
    t = '<table style="border-collapse:collapse;width:100%"><tr>' + ''.join(f'<th style="{_TH}">{x}</th>' for x in head) + '</tr>'
    for ri, r in enumerate(rows):
        bg = '#FFF0C2' if hl is not None and ri == hl else ('#F4F4F4' if ri in grey else '#fff')
        t += '<tr>' + ''.join(f'<td style="border:1.5px solid #2B2A33;padding:3px 6px;font-size:{fs}px;line-height:1.35;background:{bg};vertical-align:middle;{("width:%spx;" % widths[i]) if widths[i] else ""}">{c}</td>' for i, c in enumerate(r)) + '</tr>'
    return t + '</table>'


